import { useSyncExternalStore } from 'react';
import { effectPercentage, jellyScales } from './ui-effects';

export type MotionMode = 'slide' | 'fade' | 'off';
export type MotionPreferences = { mode: MotionMode; jelly: boolean; strength: number; reduced: boolean };
export const motionKeys = ['nexbox_page_transition', 'jelly-bounce-enabled', 'jelly-bounce-strength'] as const;
export function resolveMotion(values: Record<string, unknown>, reduced = false): MotionPreferences {
  return { mode: values[motionKeys[0]] === 'slide' || values[motionKeys[0]] === 'off' ? values[motionKeys[0]] as MotionMode : 'fade',
    jelly: values[motionKeys[1]] === true, strength: effectPercentage(values[motionKeys[2]], 200), reduced };
}
const values: Record<string, unknown> = {};
try {
  for (const key of motionKeys) {
    const raw = localStorage.getItem(key);
    if (raw !== null) values[key] = key === motionKeys[0] ? raw : JSON.parse(raw);
  }
} catch { /* An exported report can run without storage. */ }
let snapshot = resolveMotion(values, typeof matchMedia === 'function' && matchMedia('(prefers-reduced-motion: reduce)').matches);
const listeners = new Set<() => void>();
const active = new Map<HTMLElement, Animation>();
let interactionUntil = 0;
export function markMotionInteraction() { interactionUntil = Date.now() + 1500; }
export const getMotionPreferences = () => snapshot;
export function setMotionPreference(key: string, value: unknown) {
  if (!(motionKeys as readonly string[]).includes(key)) return;
  values[key] = value;
  try { localStorage.setItem(key, key === motionKeys[0] ? String(value ?? 'fade') : JSON.stringify(value ?? (key === motionKeys[1] ? false : 100))); } catch { /* Memory remains authoritative. */ }
  refreshMotion();
}
function refreshMotion() {
  const next = resolveMotion(values, typeof matchMedia === 'function' && matchMedia('(prefers-reduced-motion: reduce)').matches);
  if (JSON.stringify(next) === JSON.stringify(snapshot)) return;
  snapshot = next;
  for (const animation of active.values()) animation.cancel();
  active.clear();
  listeners.forEach(fn => fn());
}
export function subscribeMotion(fn: () => void) { listeners.add(fn); return () => { listeners.delete(fn); }; }
export function useMotionPreferences() { return useSyncExternalStore(subscribeMotion, getMotionPreferences, getMotionPreferences); }
let contentCapture: symbol | null = null;
// Fade the old composed snapshot over the live new page. Keeping the new root
// out of the capture preserves hit testing, focus and glass compositing.
export function startContentTransition(update: () => void): ViewTransition {
  const owner = Symbol('content-capture');
  contentCapture = owner;
  document.documentElement.style.viewTransitionName = 'root';
  const release = () => {
    if (contentCapture === owner) document.documentElement.style.viewTransitionName = 'none';
  };
  const transition = document.startViewTransition(() => {
    try { update(); } finally { release(); }
  });
  const interrupt = (event: Event) => {
    // Mouse boundary events can be generated by the snapshot itself. Touch
    // boundary events precede its first down event and must release it early.
    if (event.type === 'pointerover' && (event as PointerEvent).pointerType !== 'touch') return;
    transition.skipTransition();
  };
  const events = ['pointerover', 'pointermove', 'pointerdown', 'keydown', 'wheel'] as const;
  events.forEach(type => document.addEventListener(type, interrupt, { capture: true, passive: true }));
  const cleanup = () => { release(); events.forEach(type => document.removeEventListener(type, interrupt, true)); };
  void transition.finished.then(cleanup, cleanup);
  return transition;
}
export function startMotionEnvironment() {
  const updateDocument = () => { document.documentElement.dataset.motionMode=snapshot.reduced?'off':snapshot.mode; document.documentElement.dataset.motionReduced=String(snapshot.reduced); };
  updateDocument();const stopDocument=subscribeMotion(updateDocument);
  const media = matchMedia('(prefers-reduced-motion: reduce)');
  media.addEventListener('change', refreshMotion);
  const change = (event: Event) => setMotionPreference(motionKeys[0], (event as CustomEvent).detail);
  const storage = (event: StorageEvent) => {
    if (event.key && (motionKeys as readonly string[]).includes(event.key)) {
      try { values[event.key] = event.key === motionKeys[0] ? event.newValue : event.newValue === null ? undefined : JSON.parse(event.newValue); }
      catch { values[event.key] = undefined; }
      refreshMotion();
    }
  };
  window.addEventListener('page-transition-setting-changed', change);
  window.addEventListener('storage', storage);
  return () => { stopDocument();media.removeEventListener('change', refreshMotion); window.removeEventListener('page-transition-setting-changed', change); window.removeEventListener('storage', storage); };
}
export type SurfaceMotion = 'content' | 'menu' | 'drawer' | 'control';
export function surfaceFrames(prefs: MotionPreferences, entering: boolean, kind: SurfaceMotion, direction = 1): Keyframe[] {
  const translate = kind === 'menu' ? `0 ${direction * 8}px` : `${direction * (kind === 'drawer' ? 16 : 10)}px 0`;
  const off = prefs.reduced || prefs.mode === 'off';
  // Even a constant opacity animation creates a backdrop root in Chromium.
  // Glass edge filters then sample the card's own shadow until it finishes.
  // Only include opacity when it actually changes for a fade.
  const fade = !off && prefs.mode === 'fade';
  const from: Keyframe = { ...(fade ? { opacity: 0 } : {}), translate: !off && prefs.mode === 'slide' ? translate : '0 0' };
  const to: Keyframe = { ...(fade ? { opacity: 1 } : {}), translate: '0 0' };
  return entering ? [from, to] : [to, from];
}
export function playSurface(element: HTMLElement, entering = true, kind: SurfaceMotion = 'content', direction = 1): Animation | null {
  active.get(element)?.cancel();
  const prefs = kind === 'control' ? { ...snapshot, mode: 'off' as const } : snapshot;
  if (!element.animate || prefs.reduced || (prefs.mode === 'off' && (!prefs.jelly || prefs.strength === 0 || !entering))) return null;
  const jelly = entering && prefs.jelly && prefs.strength > 0;
  const frames = surfaceFrames(prefs, entering, kind, direction);
  if (jelly) {
    const scale = jellyScales(prefs.strength);
    const end = frames[1];
    const sequence = kind === 'menu' ? [scale.compression, 1, scale.small, 1] : [scale.peak, scale.compression, scale.settle, scale.small, 1];
    frames.splice(1, 1, ...sequence.map(value => ({ ...end, scale: String(value) })));
  }
  const animation = element.animate(frames, { duration: jelly ? 620 : entering ? 180 : 150, easing: 'ease-out', fill: 'both' });
  active.set(element, animation);
  const clear = () => { if (active.get(element) === animation) active.delete(element); animation.cancel(); };
  void animation.finished.then(clear, clear);
  return animation;
}

export function navigationLabels(value: unknown): boolean { return value === false || value === 'false' ? false : true; }

// Observe structural UI changes only. Text, numeric telemetry and canvas updates
// never trigger this observer; nested surfaces inherit their parent's entrance.
export function startSurfaceMotion(root: HTMLElement = document.body) {
  const selector = '.jelly-bounce-card,.jelly-bounce-tool-card,[role="tabpanel"]';
  const seen = new WeakSet<HTMLElement>();
  const reveal = (node: HTMLElement) => {
    if (!node.isConnected || node.hidden || !node.getClientRects().length || node.closest('[data-motion-owned], [data-motion-exclude]')) return;
    const parent = node.parentElement?.closest<HTMLElement>(selector);
    if (parent && !parent.hidden) return;
    if (seen.has(node)) return;
    seen.add(node);
    playSurface(node, true, node.getAttribute('role') === 'tabpanel' ? 'content' : 'control');
  };
  const scan = (node: HTMLElement) => { if(node.matches(selector)) reveal(node); node.querySelectorAll<HTMLElement>(selector).forEach(reveal); };
  const observer = new MutationObserver(records => {
    for (const record of records) {
      if(record.type === 'attributes') { const node=record.target as HTMLElement; seen.delete(node); reveal(node); }
      else if (Date.now() < interactionUntil) record.addedNodes.forEach(node => { if(node instanceof HTMLElement) scan(node); });
    }
  });
  observer.observe(root, { childList:true,subtree:true,attributes:true,attributeFilter:['hidden'] });
  const click = (event: Event) => {
    const button = (event.target as Element).closest<HTMLElement>('button,[role="button"],[role="tab"]');
    if(button && !button.closest('[data-motion-exclude]') && !button.hasAttribute('disabled')) { markMotionInteraction(); playSurface(button,true,'control'); }
  };
  root.addEventListener('click',click);
  const update = () => {
    root.dataset.motionMode=snapshot.reduced?'off':snapshot.mode;
    root.dataset.motionReduced=String(snapshot.reduced);
    root.dataset.motionJelly=String(!snapshot.reduced && snapshot.jelly && snapshot.strength > 0);
  };
  update();const stop=subscribeMotion(update);scan(root);
  return () => { observer.disconnect();root.removeEventListener('click',click);stop(); };
}
